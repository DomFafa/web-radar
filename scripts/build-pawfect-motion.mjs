// Serialize self-contained browser code before app minifiers can rename its helpers.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const target = new URL('../src/templates/themes/pawfect/motion-source.ts', import.meta.url);
let source = '// Generated by node scripts/build-pawfect-motion.mjs; edit motion.ts, then regenerate.\n';
for (const [name, fn] of [['pawfectMotionPrepareSource', 'pawfectMotionPrepare'], ['pawfectMotionSource', 'pawfectMotionRuntime']]) {
  const result = await build({ stdin: { contents: `import { ${fn} } from './src/templates/themes/pawfect/motion'; ${fn}();`, resolveDir: root, loader: 'ts' }, bundle: true, format: 'iife', platform: 'browser', target: 'es2022', keepNames: false, write: false });
  source += `export const ${name} = ${JSON.stringify(result.outputFiles[0].text)};\n`;
}
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw Error('Pawfect motion source is stale; run node scripts/build-pawfect-motion.mjs');
} else await writeFile(target, source);
