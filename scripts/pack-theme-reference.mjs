import { packedReferenceModulesEqual } from './packed-reference-check.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

const pack = (text) => gzipSync(Buffer.from(text), { level: 9 }).toString('base64');
const check = process.argv.includes('--check');

// 1. Pack referenceLayouts
{
  const refUrl = new URL('../src/templates/themes/referenceLayouts.reference.json', import.meta.url);
  const targetUrl = new URL('../src/templates/themes/referenceLayouts.ts', import.meta.url);
  const source = JSON.parse(await readFile(refUrl, 'utf8'));

  const packedHtml = Object.fromEntries(
    Object.entries(source).map(([id, layout]) => [id, pack(layout.html)]),
  );

  const layoutsCode = Object.entries(source)
    .map(([id, layout]) => {
      const meta = {
        source: layout.source,
        bodyClass: layout.bodyClass,
        htmlClass: layout.htmlClass,
        css: layout.css,
        slots: layout.slots,
      };
      return `  ${JSON.stringify(id)}: (() => {
    let override: string | undefined;
    return {
      source: ${JSON.stringify(meta.source)},
      bodyClass: ${JSON.stringify(meta.bodyClass)},
      htmlClass: ${JSON.stringify(meta.htmlClass)},
      css: ${JSON.stringify(meta.css)},
      slots: ${JSON.stringify(meta.slots)},
      get html(): string {
        return override ?? packedHtml[${JSON.stringify(id)}];
      },
      set html(value: string) {
        override = value;
      },
    };
  })(),`;
    })
    .join('\n');

  const output = `// Generated by scripts/pack-theme-reference.mjs; edit referenceLayouts.reference.json.
import { lazyReferenceText } from '../compressed-reference';

const packedHtml = lazyReferenceText(${JSON.stringify(packedHtml, null, 2)});

export const referenceLayouts = {
${layoutsCode}
};
`;

  if (check) {
    if (!packedReferenceModulesEqual(await readFile(targetUrl, 'utf8'), output)) {
      throw new Error('referenceLayouts.ts is stale; run node scripts/pack-theme-reference.mjs');
    }
  } else {
    await writeFile(targetUrl, output);
  }
  console.log(`referenceLayouts: ${Object.keys(source).length} layouts, ${Buffer.byteLength(output)} packed source bytes${check ? ' verified' : ''}`);
}

// 2. Pack Auravell
