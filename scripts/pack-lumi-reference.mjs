import { packedReferenceModulesEqual } from './packed-reference-check.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

const root = new URL('../src/templates/themes/lumi/', import.meta.url);
const pack = text => gzipSync(Buffer.from(text), { level: 9 }).toString('base64');
const check = process.argv.includes('--check');
for (const [name, exported] of [['snapshots', 'lumiSnapshots'], ['styles', 'lumiReferenceStyles']]) {
  const source = JSON.parse(await readFile(new URL(name + '.reference.json', root), 'utf8'));
  const packed = Object.fromEntries(Object.entries(source).map(([key, value]) => [key,
    typeof value === 'string' ? pack(value) : Object.fromEntries(Object.entries(value).map(([variant, html]) => [variant, pack(html)])),
  ]));
  const body = name === 'snapshots'
    ? `export const ${exported}: Record<string, Record<string, string>> = Object.fromEntries(\n  Object.entries(packed).map(([page, variants]) => [page, lazyReferenceText(variants)]),\n);\n`
    : `export const ${exported}: Record<string, string> = lazyReferenceText(packed);\n`;
  const output = '// Generated by scripts/pack-lumi-reference.mjs; edit the matching .reference.json source.\n'
    + "import { lazyReferenceText } from '../../compressed-reference';\n\n"
    + 'const packed = ' + JSON.stringify(packed, null, 2) + ';\n\n' + body;
  const target = new URL(name + '.ts', root);
  if (check) {
    if (!packedReferenceModulesEqual(await readFile(target, 'utf8'), output)) throw new Error(`${name}.ts is stale; run node scripts/pack-lumi-reference.mjs`);
  } else await writeFile(target, output);
  console.log(`${name}: ${Object.keys(source).length} pages, ${Buffer.byteLength(output)} packed source bytes${check ? ' verified' : ''}`);
}
