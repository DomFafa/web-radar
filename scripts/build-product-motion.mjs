// Serialize browser entry points before application minifiers can rename their helpers.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const target = new URL('../src/templates/themes/product-motion-source.ts', import.meta.url);
let source = '// Generated by node scripts/build-product-motion.mjs; edit product-motion.ts, then regenerate.\n';
for (const [name, fn] of [['productMotionPrepareSource', 'productMotionPrepare'], ['productMotionSource', 'productMotionRuntime']]) {
  const result = await build({ stdin: { contents: `import { ${fn} } from './src/templates/themes/product-motion'; ${fn}();`, resolveDir: root, loader: 'ts' }, bundle: true, format: 'iife', platform: 'browser', target: 'es2022', keepNames: false, minify: true, write: false });
  source += `export const ${name} = ${JSON.stringify(result.outputFiles[0].text)};\n`;
}
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw Error('Product motion source is stale; run node scripts/build-product-motion.mjs');
} else await writeFile(target, source);
